import streamlit as st

st.header("📘 ثانياً: عن النظام - المنهجية والمراجع")

st.subheader("كيف يعمل النظام؟")
st.markdown("""
يعتمد النظام على مقارنة القراءات الميدانية المُدخلة يدوياً مع القيم المرجعية
المدونة على ملصق اللوح الشمسي أو داتاشيت البطارية، بعد تصحيح تأثير ظروف
القياس الفعلية (الحرارة والإشعاع) لتصبح مكافئة لظروف الاختبار القياسية.
""")

st.markdown("---")

st.subheader("⚡ منهجية فحص اللوح الشمسي")
st.markdown("""
**1. تصحيح القراءات لظروف الاختبار القياسية (STC):**

القراءة الميدانية تُقاس عند حرارة وإشعاع مختلفين عن ظروف المصنع (25°C، 1000 W/m²)،
لذلك يجب تصحيحها أولاً قبل أي مقارنة:
""")
st.latex(r"V_{oc,STC} = \dfrac{V_{oc,measured}}{1 + \dfrac{\beta}{100}\,(T_{measured} - 25)}")
st.latex(r"I_{sc,STC} = I_{sc,measured} \cdot \dfrac{1000}{G_{measured}} \Big/ \left(1 + \dfrac{\alpha}{100}\,(T_{measured} - 25)\right)")

st.markdown("""
**2. حساب الكفاءة ومعامل الملء (Fill Factor):**
""")
st.latex(r"Efficiency = \dfrac{V_{mp} \times I_{mp}}{P_{rated}} \times 100")
st.latex(r"FF = \dfrac{V_{mp} \times I_{mp}}{V_{oc,STC} \times I_{sc,STC}}")

st.markdown("""
**3. تصنيف الحالة:**

| الكفاءة | التصنيف |
|---|---|
| 80% فأكثر | ممتازة / جيدة جداً |
| 65% - 79% | تحذير مبكر - بداية تراجع |
| أقل من 65% | انخفاض واضح - يعرض احتمالات السبب |

**4. جدول ترجيح الاحتمالات عند وجود انخفاض:**

| نمط الانحراف | الاحتمال الأقرب |
|---|---|
| Isc منخفض و Voc طبيعي | تظليل جزئي أو اتساخ على السطح |
| Voc منخفض بشكل حاد و Isc طبيعي | عطل في دايود التمرير أو انقطاع بالتوصيل |
| Voc و Isc طبيعيان لكن FF منخفض | مقاومة توالي عالية (لحام / وصلات ضعيفة) |
| Isc و FF منخفضان معاً | تشققات دقيقة في الخلايا |
| انخفاض طفيف وعام في كل القيم | تدهور طبيعي مرتبط بعمر اللوح |
""")

st.markdown("---")

st.subheader("🔋 منهجية فحص البطارية")
st.markdown("""
تعتمد حالة صحة البطارية (SoH) على مقارنة المقاومة الداخلية المقاسة حالياً
بمقاومتها وهي جديدة، مع الأخذ بعين الاعتبار عدد دورات الشحن مقارنة
بالعدد المتوقع من الداتاشيت.
""")
st.latex(r"SoH = 100 - \dfrac{(R_{int} - R_{new})}{R_{new}} \times 50")

st.markdown("""
| نمط الانحراف | الاحتمال الأقرب |
|---|---|
| مقاومة مرتفعة مع دورات قليلة نسبياً | التملح (Sulfation) بسبب الشحن الجزئي المتكرر |
| عدد الدورات تجاوز الحد المتوقع | نهاية العمر الافتراضي الطبيعي |
| مقاومة مرتفعة جداً مع دورات قليلة جداً | خلية ضعيفة أو مشكلة في الوصلات الداخلية |
""")

st.markdown("---")

