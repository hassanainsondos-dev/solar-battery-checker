st.subheader("Battery - من وين تجيب قراءات البطارية")

st.markdown("""
**المقاومة الداخلية (Internal Resistance):**
تُقاس بجهاز مخصص اسمه **Battery Internal Resistance Tester** (رخيص ومتوفر بمحلات
الإلكترونيات)، بس توصّله على طرفي البطارية وبيعطيك القراءة مباشرة بالـ milliOhm.

**عدد دورات الشحن:**
للبطاريات الليثيوم الحديثة، عدد الدورات موجود عادة على شاشة الـ **BMS**
(نظام إدارة البطارية) أو تطبيق المراقبة المرافق للبطارية. لبطاريات الرصاص الحمضية
العادية ما في عدّاد، فتقدر تقدّرها حسب تاريخ التركيب وعدد مرات الاستخدام اليومية
التقريبية.

**القيم المرجعية (المقاومة الجديدة، عدد الدورات المتوقع):**
موجودة على ملصق البطارية أو الداتاشيت من الشركة المصنعة. إذا نوع بطاريتك موجود
بالقائمة بالصفحة، اختاره وبتنعبى القيم تلقائياً.
""")

st.markdown("---")

st.subheader("Methodology - كيف يحسب النظام")

st.markdown("**Step 1 - STC Correction (تصحيح ظروف القياس):**")
st.latex(r"V_{oc,STC} = \dfrac{V_{oc,measured}}{1 + \dfrac{\beta}{100}(T_{measured} - 25)}")
st.latex(r"I_{sc,STC} = I_{sc,measured} \cdot \dfrac{1000}{G_{measured}} \Big/ \left(1 + \dfrac{\alpha}{100}(T_{measured}-25)\right)")

st.markdown("**Step 2 - Efficiency and Fill Factor:**")
st.latex(r"Efficiency = \dfrac{V_{mp}\times I_{mp}}{P_{rated}}\times 100")
st.latex(r"FF = \dfrac{V_{mp}\times I_{mp}}{V_{oc,STC}\times I_{sc,STC}}")

st.markdown("**Battery State of Health:**")
st.latex(r"SoH = 100 - \dfrac{(R_{int}-R_{new})}{R_{new}}\times 50")

