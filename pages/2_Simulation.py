st.subheader("Solar Panel - من وين تجيب قراءات اللوح الشمسي")

st.markdown("""
**Voc (فولتية الدارة المفتوحة):**
افصل اللوح تماماً عن أي حمل أو جهاز شحن، وثبّت طرفي جهاز الـ multimeter (على وضع قياس
الفولت DC) على طرفي اللوح الموجب والسالب مباشرة. الرقم اللي بيطلع هو Voc.

**Isc (تيار الدارة القصيرة):**
حوّل الـ multimeter لوضع قياس التيار DC، ووصّل طرفي اللوح ببعض عن طريق الجهاز مباشرة
(الجهاز نفسه بيصير المسار). **مهم:** تأكد إن الجهاز يتحمل تيار أعلى من Isc المتوقع للوح،
وخذ القراءة بسرعة.

**Vmp و Imp (الفولتية والتيار عند أقصى قدرة):**
هاي أسهل توخذها من شاشة **جهاز شحن البطارية (Charge Controller)** أو الـ **Inverter**
المتصل باللوح، لأنه بيعرض القراءات اللحظية أثناء التشغيل الطبيعي. إذا ما في عندك هيك جهاز،
قدر تقريبي: Vmp ≈ 0.8 × Voc و Imp ≈ 0.9 × Isc.

**درجة الحرارة وحالة الطقس:**
درجة حرارة الجو تقدر تاخذها من أي تطبيق طقس بالموبايل وقت القياس. حالة الطقس (مشمس/غائم)
اختارها من القائمة بالصفحة، والموقع بيحول هذا لقيمة تقريبية لشدة الإشعاع تلقائياً.

**بيانات اللوح (Voc, Isc, Pmax المدونة):**
موجودة على **ملصق فني ملزوج بظهر اللوح** يحتوي: Model, Pmax, Voc, Isc, Vmp, Imp,
Tolerance. إذا موديلك موجود بالقائمة بالصفحة، اختاره وبتنعبى القيم تلقائياً.
معاملات الحرارة (Alpha, Beta) عادة مش على الملصق العادي، وموجودة بس بالداتاشيت
الكامل (PDF) من موقع الشركة المصنعة - إذا مش متوفر عندك، الموقع بيستخدم قيم
افتراضية شائعة تلقائياً.
""")

